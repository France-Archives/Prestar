-- Fix identity sequences after imported explicit IDs so future inserts cannot
-- collide with existing rows. Empty-table sequences remain ready to issue 1.
DO $$
DECLARE item RECORD;
DECLARE maximum_id BIGINT;
BEGIN
  FOR item IN SELECT * FROM (VALUES
    ('authors','author_id'), ('book_copies','copy_id'), ('books','book_id'),
    ('borrow_requests','request_id'), ('borrowed_books','borrow_id'), ('categories','category_id'),
    ('colleges','college_id'), ('courses','course_id'), ('notifications','notification_id'),
    ('penalties','penalty_id'), ('reservations','reservation_id'), ('returned_books','return_id'),
    ('signup_verifications','verification_id'), ('signups','signup_id'), ('suspensions','suspension_id'),
    ('user_category_preferences','preference_id'), ('users','user_id')
  ) AS identity_columns(table_name,column_name)
  LOOP
    EXECUTE format('SELECT max(%I) FROM public.%I', item.column_name, item.table_name) INTO maximum_id;
    PERFORM setval(
      pg_get_serial_sequence(format('public.%I', item.table_name), item.column_name),
      COALESCE(maximum_id, 1),
      maximum_id IS NOT NULL
    );
  END LOOP;
END $$;

