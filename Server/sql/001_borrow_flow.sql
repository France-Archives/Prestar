-- Server/sql/001_borrow_flow.sql
-- Non-destructive reconciliation for the current database and online_book.sql.
-- Does not drop tables or overwrite data. Preserves the target-only colleges,
-- courses, students, users, signups, and signup-verification rows.
BEGIN;

-- Historical signup requests were created while signup_id had no primary key
-- and its identity sequence was out of sync. Keep every row: retain the first
-- ID in each duplicate group and move later rows to fresh IDs. Remap each audit
-- event to the closest preceding signup with that old ID before changing IDs.
CREATE TEMP TABLE _signup_id_repair ON COMMIT DROP AS
WITH ranked AS (
  SELECT signup_id AS old_signup_id,
         reference_no,
         created_at,
         row_number() OVER (PARTITION BY signup_id ORDER BY created_at, reference_no) AS duplicate_rank,
         max(signup_id) OVER () AS max_signup_id,
         row_number() OVER (ORDER BY created_at, reference_no) AS repair_rank
  FROM public.signups
)
SELECT old_signup_id,
       reference_no,
       created_at,
       CASE WHEN duplicate_rank = 1 THEN old_signup_id
          ELSE max_signup_id + repair_rank END AS repaired_signup_id
FROM ranked;

ALTER TABLE public.signup_verifications ALTER COLUMN verification_id SET GENERATED BY DEFAULT;
UPDATE public.signup_verifications AS verification
SET signup_id = (
  SELECT mapping.repaired_signup_id
  FROM _signup_id_repair AS mapping
  WHERE mapping.old_signup_id = verification.signup_id
    AND mapping.created_at <= verification.created_at
  ORDER BY mapping.created_at DESC, mapping.reference_no
  LIMIT 1
)
WHERE verification.signup_id IN (
  SELECT old_signup_id FROM _signup_id_repair GROUP BY old_signup_id HAVING count(*) > 1
);

ALTER TABLE public.signups ALTER COLUMN signup_id SET GENERATED BY DEFAULT;
UPDATE public.signups AS signup
SET signup_id = repair.repaired_signup_id
FROM _signup_id_repair AS repair
WHERE signup.reference_no = repair.reference_no
  AND signup.signup_id IS DISTINCT FROM repair.repaired_signup_id;
ALTER TABLE public.signups ALTER COLUMN signup_id SET GENERATED ALWAYS;

-- Verification IDs also collided because their sequence was not advanced.
WITH ranked AS (
  SELECT ctid,
         verification_id,
         created_at,
         row_number() OVER (PARTITION BY verification_id ORDER BY created_at, signup_id, action) AS duplicate_rank,
         max(verification_id) OVER () AS max_id,
         row_number() OVER (ORDER BY created_at, signup_id, action) AS repair_rank
  FROM public.signup_verifications
)
UPDATE public.signup_verifications AS verification
SET verification_id = ranked.max_id + ranked.repair_rank
FROM ranked
WHERE verification.ctid = ranked.ctid
  AND ranked.duplicate_rank > 1;
ALTER TABLE public.signup_verifications ALTER COLUMN verification_id SET GENERATED ALWAYS;

